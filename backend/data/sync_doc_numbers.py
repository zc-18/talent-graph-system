def main():
    cov = sys.argv[1] if len(sys.argv) > 1 else "65"
    by_file: dict[str, list] = {}
    for fn, old, new in EDITS:
        by_file.setdefault(fn, []).append((old, new.replace("__COV__", cov)))

    failed = []
    for fn, pairs in by_file.items():
        p = DOCS / fn
        text = p.read_text(encoding="utf-8")
        for old, new in pairs:
            n = text.count(old)
            if n != 1:
                failed.append(f"{fn}: 命中 {n} 次（应为 1）→ {old[:60]}...")
                continue
            text = text.replace(old, new)
        p.write_text(text, encoding="utf-8")
        print(f"[ok] {fn} 应用 {len(pairs)} 处")

    if failed:
        print("\n以下替换未生效，需人工核对：")
        for f in failed:
            print("  ", f)
        sys.exit(1)
    print("\n全部替换成功")


if __name__ == "__main__":
    main()
