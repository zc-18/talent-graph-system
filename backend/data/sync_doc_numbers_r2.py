def main():
    by_file: dict[str, list] = {}
    for fn, old, new in EDITS:
        by_file.setdefault(fn, []).append((old, new))

    failed, applied = [], 0
    staged: dict[Path, str] = {}
    for fn, pairs in by_file.items():
        p = DOCS / fn
        text = p.read_text(encoding="utf-8")
        ok = 0
        for old, new in pairs:
            n = text.count(old)
            if n != 1:
                failed.append(f"{fn}: 命中 {n} 次（应为 1）→ {old[:70]}...")
                continue
            text = text.replace(old, new)
            ok += 1
        staged[p] = text
        applied += ok
        print(f"[{'ok' if ok == len(pairs) else '部分'}] {fn}  {ok}/{len(pairs)}")

    if failed:
        print("\n以下替换未生效，**未写盘**，需人工核对：")
        for f in failed:
            print("  ", f)
        sys.exit(1)
    for p, text in staged.items():
        p.write_text(text, encoding="utf-8")
    print(f"\n全部 {applied} 处替换成功，已写盘")


if __name__ == "__main__":
    main()
